"""Regression coverage for Windows-corrupted release-please PR envelopes."""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path
from types import SimpleNamespace

import pytest

SCRIPT = Path(__file__).resolve().parents[1] / "normalize_release_pr_bodies.py"


def load_module():
    spec = importlib.util.spec_from_file_location("normalize_release_pr_bodies", SCRIPT)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


BODY = ":robot: I have created a release *beep* *boop*\n\n---\n\n## [0.43.0](url)\n\n- fix\n\n---\n\nGenerated by Release Please.\n"


@pytest.mark.parametrize("ending", ["\n", "\r\n", "\r\r\n", "\r\r\r\n"])
def test_normalization_restores_exact_release_please_delimiters(ending):
    module = load_module()
    damaged = BODY.replace("\n", ending)
    # This is release-please's splitBody normalization: an extra CR survives.
    if ending.count("\r") > 1:
        assert "---" not in damaged.strip().replace("\r\n", "\n").split("\n")
    assert module.normalize_body(damaged) == BODY


def pending_release(**overrides):
    pr = {
        "number": 4643,
        "merged_at": "2026-11-05T16:35:16Z",
        "base": {"ref": "main"},
        "head": {
            "ref": "release-please--branches--main--components--headroom-ai",
            "repo": {"full_name": "owner/repo"},
        },
        "user": {"type": "Bot"},
        "labels": [{"name": "autorelease: pending"}],
        "body": BODY.replace("\n", "\r\r\n"),
    }
    return {**pr, **overrides}


def test_dry_run_never_writes(monkeypatch):
    module = load_module()
    monkeypatch.setattr(
        module, "github_json", lambda *args, **kwargs: pytest.fail("unexpected write")
    )
    assert module.repair_release("owner/repo", pending_release(), apply=False)


def test_api_write_uses_json_stdin_without_windows_text_file_roundtrip(monkeypatch):
    module = load_module()
    calls = []

    def run(command, **kwargs):
        calls.append((command, kwargs))
        return SimpleNamespace(stdout="{}")

    monkeypatch.setattr(module.subprocess, "run", run)
    module.github_json("repos/owner/repo/pulls/4643", body=BODY)
    command, kwargs = calls[0]
    assert command[-4:] == ["--method", "PATCH", "--input", "-"]
    assert module.json.loads(kwargs["input"])["body"] == BODY


def test_workflow_repairs_before_release_detection():
    workflow = SCRIPT.parents[1] / ".github" / "workflows" / "release-please.yml"
    source = workflow.read_text(encoding="utf-8")
    assert source.index("python scripts/normalize_release_pr_bodies.py") < source.index(
        "uses: googleapis/release-please-action"
    )
    assert '--repo "${{ github.repository }}" --apply' in source


def test_repairs_only_merged_pending_release_prs(monkeypatch):
    module = load_module()
    calls = []
    monkeypatch.setattr(
        module, "github_json", lambda endpoint, **kwargs: calls.append((endpoint, kwargs))
    )
    assert module.repair_release("owner/repo", pending_release())
    assert calls == [("repos/owner/repo/pulls/4643", {"body": BODY})]


@pytest.mark.parametrize(
    "overrides",
    [
        {"merged_at": None},
        {"labels": [{"name": "autorelease: tagged"}]},
        {"base": {"ref": "maintenance"}},
        {"head": {"ref": "contributor-feature"}},
        {"user": {"type": "User"}},
        {
            "head": {
                "ref": "release-please--branches--main--components--headroom-ai",
                "repo": {"full_name": "someone/fork"},
            }
        },
        {"body": BODY},
        {"body": BODY.replace("\n", "\r\n")},
    ],
)
def test_does_not_edit_unrelated_or_already_valid_prs(monkeypatch, overrides):
    module = load_module()
    monkeypatch.setattr(
        module, "github_json", lambda *args, **kwargs: pytest.fail("unexpected write")
    )
    assert not module.repair_release("owner/repo", pending_release(**overrides))


def test_missing_release_envelope_fails_instead_of_silently_making_another_release(monkeypatch):
    module = load_module()
    monkeypatch.setattr(
        module, "github_json", lambda *args, **kwargs: pytest.fail("unexpected write")
    )
    with pytest.raises(ValueError, match="4643.*release-please envelope"):
        module.repair_release(
            "owner/repo", pending_release(body="Oversized notes are elsewhere.\r\r\n")
        )
